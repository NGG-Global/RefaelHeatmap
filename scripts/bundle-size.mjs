// Gzipped size of what each route downloads (run after `npm run build`).
//   npm run size              # print
//   npm run size -- --write   # also write docs/bundle-size.md
import { readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { brotliCompressSync, gzipSync } from "node:zlib";

const DIST = "dist";
const manifest = JSON.parse(readFileSync(join(DIST, ".vite", "manifest.json"), "utf8"));

const ROUTES = [
  ["/v/:shortCode (participant)", "src/modules/heatmap/participant/ParticipantPage.tsx"],
  ["/heatmap/display/:eventId", "src/modules/heatmap/display/DisplayPage.tsx"],
  ["/heatmap/host", "src/modules/heatmap/host/HostPage.tsx"],
];
const FONTS = ["fonts/assistant-hebrew-v1.woff2", "fonts/assistant-latin-v1.woff2"];

function collect(key, js, css) {
  const chunk = manifest[key];
  if (!chunk || js.has(chunk.file)) return;
  js.add(chunk.file);
  for (const c of chunk.css ?? []) css.add(c);
  for (const imp of chunk.imports ?? []) collect(imp, js, css);
}

const size = (files, fn) => [...files].reduce((sum, f) => sum + fn(readFileSync(join(DIST, f))).length, 0);
const gz = (b) => gzipSync(b, { level: 9 });
const br = (b) => brotliCompressSync(b);
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;

const rows = ROUTES.map(([label, key]) => {
  const js = new Set();
  const css = new Set();
  collect("index.html", js, css);
  collect(key, js, css);
  return { label, jsGzip: size(js, gz), jsBrotli: size(js, br), cssGzip: size(css, gz), files: [...js] };
});
const html = gz(readFileSync(join(DIST, "index.html"))).length;
const fonts = FONTS.reduce((s, f) => s + statSync(join(DIST, f)).size, 0);

const lines = [
  "| Route | JS (gzip) | JS (brotli) | CSS (gzip) |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.label} | ${kb(r.jsGzip)} | ${kb(r.jsBrotli)} | ${kb(r.cssGzip)} |`),
];
const participant = rows[0];
const total = participant.jsGzip + participant.cssGzip + html + fonts;
const summary = [
  `Participant first load: ${kb(total)} in total = JS ${kb(participant.jsGzip)} + CSS ${kb(participant.cssGzip)} + HTML ${kb(html)} + fonts ${kb(fonts)} (woff2, already compressed).`,
  `Participant JS files: ${participant.files.join(", ")}.`,
  "The participant route contains no supabase-js (plain fetch to PostgREST); supabase-js ships only in the display/host chunk.",
];

console.log(lines.join("\n"));
console.log("\n" + summary.join("\n"));

if (process.argv.includes("--write")) {
  const doc = [
    "# Bundle size report",
    "",
    "Generated by `npm run size -- --write` after `npm run build`. Sizes are what",
    "a browser downloads for each route on a cold cache (entry chunk + route",
    "chunk + their static imports).",
    "",
    ...lines,
    "",
    ...summary.map((s) => `- ${s}`),
    "",
  ].join("\n");
  writeFileSync("docs/bundle-size.md", doc);
  console.log("\nWrote docs/bundle-size.md");
}
